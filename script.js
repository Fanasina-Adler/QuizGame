function startTime() {
    clearInterval(intervalTime);

    restTime = 15;
    sec.textContent = 15;

    intervalTime = setInterval(() => {
        restTime--;

        sec.textContent = restTime < 10 ? "0" + restTime : restTime;

        if (restTime <= 0) {
            clearInterval(intervalTime);
            intervalTime = null;

            questionRepondu++;
            changeQuestion();
        }
    }, 1000);
}


